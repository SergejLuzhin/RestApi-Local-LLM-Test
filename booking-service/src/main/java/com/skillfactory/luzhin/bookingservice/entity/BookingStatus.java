package com.skillfactory.luzhin.bookingservice.entity;

/**
 * Перечисление статусов бронирования.
 *
 * Определяет жизненный цикл бронирования в рамках двухшаговой распределённой транзакции:
 * PENDING — бронирование создано, ожидает подтверждения доступности номера от Hotel Service;
 * CONFIRMED — номер подтверждён, бронирование завершено успешно;
 * CANCELLED — бронирование отменено (ошибка подтверждения, таймаут или ручная отмена пользователем).
 */
public enum BookingStatus {

    /**
     * Статус «В ожидании подтверждения».
     * Бронирование создано локально, но ещё не подтверждено Hotel Service.
     */
    PENDING,

    /**
     * Статус «Подтверждено».
     * Номер успешно подтверждён Hotel Service, бронирование активно.
     */
    CONFIRMED,

    /**
     * Статус «Отменено».
     * Бронирование отменено из-за ошибки подтверждения, таймаута или по запросу пользователя.
     */
    CANCELLED
}
