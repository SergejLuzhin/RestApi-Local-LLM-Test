package com.skillfactory.luzhin.bookingservice.entity;

/**
 * Перечисление ролей пользователей в системе.
 *
 * Определяет два уровня доступа:
 * USER — обычные пользователи, которые могут регистрироваться,
 *         просматривать отели и создавать бронирования;
 * ADMIN — администраторы, которые могут управлять отелями,
 *          номерами и пользователями.
 */
public enum UserRole {

    /**
     * Роль обычного пользователя.
     * Имеет доступ к личным операциям: регистрация, просмотр отелей, бронирование.
     */
    USER,

    /**
     * Роль администратора.
     * Имеет доступ к управлению: CRUD отелей, номеров и пользователей.
     */
    ADMIN
}
